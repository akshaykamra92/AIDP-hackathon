-- Optional synthetic sources for the portable RATIO_SUM example.
-- Run once after the security installer, or rerun safely: MERGE only inserts
-- missing demo IDs. No organization or person records are used.

CREATE TABLE IF NOT EXISTS WH_EXAMPLE_SITE (
    SITE_CODE VARCHAR2(20) CONSTRAINT WH_EX_SITE_PK PRIMARY KEY,
    STATE_CODE CHAR(2) NOT NULL
);

CREATE TABLE IF NOT EXISTS WH_EXAMPLE_ORDER (
    ORDER_ID NUMBER(10) CONSTRAINT WH_EX_ORDER_PK PRIMARY KEY,
    CHANNEL VARCHAR2(30) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS WH_EXAMPLE_ORDER_LINE (
    ORDER_ID NUMBER(10) NOT NULL,
    LINE_NO NUMBER(5) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    CONSTRAINT WH_EX_LINE_PK PRIMARY KEY (ORDER_ID, LINE_NO),
    CONSTRAINT WH_EX_LINE_ORDER_FK FOREIGN KEY (ORDER_ID) REFERENCES WH_EXAMPLE_ORDER (ORDER_ID),
    CONSTRAINT WH_EX_LINE_QTY_CK CHECK (QUANTITY > 0)
);

CREATE TABLE IF NOT EXISTS WH_EXAMPLE_SHIPMENT (
    SHIPMENT_ID NUMBER(10) CONSTRAINT WH_EX_SHIP_PK PRIMARY KEY,
    ORDER_ID NUMBER(10) NOT NULL CONSTRAINT WH_EX_SHIP_ORDER_UK UNIQUE,
    FULFILLED_AT DATE NOT NULL,
    PROMISED_AT DATE NOT NULL,
    SITE_CODE_AT_FULFILLMENT VARCHAR2(20) NOT NULL,
    CONSTRAINT WH_EX_SHIP_ORDER_FK FOREIGN KEY (ORDER_ID) REFERENCES WH_EXAMPLE_ORDER (ORDER_ID),
    CONSTRAINT WH_EX_SHIP_SITE_FK FOREIGN KEY (SITE_CODE_AT_FULFILLMENT) REFERENCES WH_EXAMPLE_SITE (SITE_CODE)
);

MERGE INTO WH_EXAMPLE_SITE target
USING (
    SELECT 'DEMO-A' SITE_CODE, 'FL' STATE_CODE FROM DUAL
    UNION ALL SELECT 'DEMO-B', 'AL' FROM DUAL
) source ON (target.SITE_CODE = source.SITE_CODE)
WHEN NOT MATCHED THEN INSERT (SITE_CODE, STATE_CODE)
VALUES (source.SITE_CODE, source.STATE_CODE);

MERGE INTO WH_EXAMPLE_ORDER target
USING (
    SELECT 1001 ORDER_ID, 'DIRECT' CHANNEL, 'FILLED' STATUS FROM DUAL
    UNION ALL SELECT 1002, 'DIRECT', 'FILLED' FROM DUAL
    UNION ALL SELECT 1003, 'PARTNER', 'FILLED' FROM DUAL
    UNION ALL SELECT 1004, 'PARTNER', 'FILLED' FROM DUAL
    UNION ALL SELECT 1005, 'DIRECT', 'FILLED' FROM DUAL
    UNION ALL SELECT 1006, 'DIRECT', 'CANCELLED' FROM DUAL
) source ON (target.ORDER_ID = source.ORDER_ID)
WHEN NOT MATCHED THEN INSERT (ORDER_ID, CHANNEL, STATUS)
VALUES (source.ORDER_ID, source.CHANNEL, source.STATUS);

MERGE INTO WH_EXAMPLE_ORDER_LINE target
USING (
    SELECT 1001 ORDER_ID, 1 LINE_NO, 2 QUANTITY FROM DUAL
    UNION ALL SELECT 1001, 2, 1 FROM DUAL
    UNION ALL SELECT 1002, 1, 3 FROM DUAL
    UNION ALL SELECT 1003, 1, 1 FROM DUAL
    UNION ALL SELECT 1004, 1, 1 FROM DUAL
    UNION ALL SELECT 1005, 1, 2 FROM DUAL
) source ON (target.ORDER_ID = source.ORDER_ID AND target.LINE_NO = source.LINE_NO)
WHEN NOT MATCHED THEN INSERT (ORDER_ID, LINE_NO, QUANTITY)
VALUES (source.ORDER_ID, source.LINE_NO, source.QUANTITY);

MERGE INTO WH_EXAMPLE_SHIPMENT target
USING (
    SELECT 2001 SHIPMENT_ID, 1001 ORDER_ID, DATE '2026-07-15' FULFILLED_AT,
           DATE '2026-07-16' PROMISED_AT, 'DEMO-A' SITE_CODE_AT_FULFILLMENT FROM DUAL
    UNION ALL SELECT 2002, 1002, DATE '2026-08-05', DATE '2026-08-01', 'DEMO-A' FROM DUAL
    UNION ALL SELECT 2003, 1003, DATE '2026-09-10', DATE '2026-09-10', 'DEMO-A' FROM DUAL
    UNION ALL SELECT 2004, 1004, DATE '2026-07-20', DATE '2026-07-19', 'DEMO-B' FROM DUAL
    UNION ALL SELECT 2005, 1005, DATE '2026-09-05', DATE '2026-09-06', 'DEMO-B' FROM DUAL
) source ON (target.SHIPMENT_ID = source.SHIPMENT_ID)
WHEN NOT MATCHED THEN INSERT (
    SHIPMENT_ID, ORDER_ID, FULFILLED_AT, PROMISED_AT, SITE_CODE_AT_FULFILLMENT
) VALUES (
    source.SHIPMENT_ID, source.ORDER_ID, source.FULFILLED_AT,
    source.PROMISED_AT, source.SITE_CODE_AT_FULFILLMENT
);
