-- Ask the Warehouse: read-only verification after 01_schema.sql and 02_seed.sql.
-- Expected counts: 6 locations, 2000 employees, 240 events, 432 snapshots,
-- 360 requisitions, 5 certified metrics, 0 requests, 0 answer logs.

SELECT 'WH_LOCATION' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM WH_LOCATION
UNION ALL SELECT 'WH_EMPLOYEE', COUNT(*) FROM WH_EMPLOYEE
UNION ALL SELECT 'WH_TERMINATION', COUNT(*) FROM WH_TERMINATION
UNION ALL SELECT 'WH_HEADCOUNT_MONTH', COUNT(*) FROM WH_HEADCOUNT_MONTH
UNION ALL SELECT 'WH_REQUISITION', COUNT(*) FROM WH_REQUISITION
UNION ALL SELECT 'WH_METRIC', COUNT(*) FROM WH_METRIC
UNION ALL SELECT 'WH_METRIC_REQUEST', COUNT(*) FROM WH_METRIC_REQUEST
UNION ALL SELECT 'WH_ANSWER_LOG', COUNT(*) FROM WH_ANSWER_LOG;

-- Expected: 2025-04-01 to 2026-09-01, 18 months, 432 rows.
SELECT MIN(MONTH_START) AS FIRST_MONTH,
       MAX(MONTH_START) AS LAST_MONTH,
       COUNT(DISTINCT MONTH_START) AS MONTHS,
       COUNT(*) AS SNAPSHOT_ROWS
FROM WH_HEADCOUNT_MONTH;

-- Expected: no rows. Every location/job combination has 18 months.
SELECT LOCATION_ID, JOB_FAMILY, COUNT(*) AS MONTHS
FROM WH_HEADCOUNT_MONTH
GROUP BY LOCATION_ID, JOB_FAMILY
HAVING COUNT(*) <> 18;

-- Expected: every catalog entry is CERTIFIED, version 1, and marker = METRIC_ID.
SELECT METRIC_ID, NAME, STATUS, VERSION,
       DBMS_LOB.SUBSTR(SQL_TEMPLATE, 40, 1) AS TEMPLATE_MARKER,
       ALLOWED_DIMS, ALLOWED_FILTERS
FROM WH_METRIC
ORDER BY METRIC_ID;

-- Expected Q3 2026 FL: 21 events, 4 internal transfers, 17 approved exits.
-- Avg monthly EOM headcount = 901.6667; certified = 1.89%, naive = 2.33%.
-- The naive rate counts INTERNAL_TRANSFER and is for demo contrast only.
WITH periods AS (
    SELECT 'ALL HISTORY' AS PERIOD_NAME,
           DATE '2025-04-01' AS START_DATE, DATE '2026-10-01' AS END_DATE FROM DUAL
    UNION ALL
    SELECT 'Q3 2026', DATE '2026-07-01', DATE '2026-10-01' FROM DUAL
), monthly_headcount AS (
    SELECT p.PERIOD_NAME, h.MONTH_START, SUM(h.HEADCOUNT) AS HEADCOUNT
    FROM periods p
    JOIN WH_HEADCOUNT_MONTH h
      ON h.MONTH_START >= p.START_DATE AND h.MONTH_START < p.END_DATE
    JOIN WH_LOCATION l ON l.LOCATION_ID = h.LOCATION_ID
    WHERE l.STATE = 'FL'
    GROUP BY p.PERIOD_NAME, h.MONTH_START
), denominator AS (
    SELECT PERIOD_NAME, AVG(HEADCOUNT) AS AVG_MONTHLY_HEADCOUNT
    FROM monthly_headcount
    GROUP BY PERIOD_NAME
), events AS (
    SELECT p.PERIOD_NAME,
           COUNT(*) AS ALL_EVENTS,
           SUM(CASE WHEN t.TERM_TYPE = 'INTERNAL_TRANSFER' THEN 1 ELSE 0 END) AS INTERNAL_TRANSFERS,
           SUM(CASE WHEN t.TERM_TYPE <> 'INTERNAL_TRANSFER' THEN 1 ELSE 0 END) AS APPROVED_EXITS
    FROM periods p
    JOIN WH_TERMINATION t
      ON t.TERM_DATE >= p.START_DATE AND t.TERM_DATE < p.END_DATE
    JOIN WH_LOCATION l ON l.LOCATION_ID = t.LOCATION_ID
    WHERE l.STATE = 'FL'
    GROUP BY p.PERIOD_NAME
)
SELECT e.PERIOD_NAME,
       e.ALL_EVENTS,
       e.INTERNAL_TRANSFERS,
       e.APPROVED_EXITS,
       ROUND(d.AVG_MONTHLY_HEADCOUNT, 2) AS AVG_MONTHLY_HEADCOUNT,
       ROUND(100 * e.APPROVED_EXITS / NULLIF(d.AVG_MONTHLY_HEADCOUNT, 0), 2) AS CERTIFIED_TURNOVER_PCT,
       ROUND(100 * e.ALL_EVENTS / NULLIF(d.AVG_MONTHLY_HEADCOUNT, 0), 2) AS NAIVE_TURNOVER_PCT
FROM events e
JOIN denominator d ON d.PERIOD_NAME = e.PERIOD_NAME
ORDER BY e.PERIOD_NAME;

-- Expected: 33 events where historical location differs from current roster location.
SELECT COUNT(*) AS TRANSFER_EVENTS_WITH_HISTORICAL_LOCATION
FROM WH_TERMINATION t
JOIN WH_EMPLOYEE e ON e.EMP_ID = t.EMP_ID
WHERE t.TERM_TYPE = 'INTERNAL_TRANSFER'
  AND t.LOCATION_ID <> e.LOCATION_ID;

-- Expected: 288 filled requisitions, 72 internal fills; Q3 has 36 filled, 7 internal.
SELECT COUNT(*) AS FILLED_REQUISITIONS,
       SUM(CASE WHEN FILLED_INTERNALLY = 'Y' THEN 1 ELSE 0 END) AS INTERNAL_FILLS,
       MEDIAN(FILL_DATE - OPEN_DATE) AS MEDIAN_TIME_TO_FILL_DAYS
FROM WH_REQUISITION
WHERE FILL_DATE IS NOT NULL;

SELECT COUNT(*) AS Q3_FILLED_REQUISITIONS,
       SUM(CASE WHEN FILLED_INTERNALLY = 'Y' THEN 1 ELSE 0 END) AS Q3_INTERNAL_FILLS,
       ROUND(100 * SUM(CASE WHEN FILLED_INTERNALLY = 'Y' THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0), 2)
           AS Q3_INTERNAL_FILL_PCT,
       MEDIAN(FILL_DATE - OPEN_DATE) AS Q3_MEDIAN_TIME_TO_FILL_DAYS
FROM WH_REQUISITION
WHERE FILL_DATE >= DATE '2026-07-01'
  AND FILL_DATE < DATE '2026-10-01';

-- Expected: eight tables with four table-level annotations each.
SELECT OBJECT_NAME, COUNT(*) AS TABLE_ANNOTATIONS
FROM USER_ANNOTATIONS_USAGE
WHERE OBJECT_NAME IN ('WH_LOCATION', 'WH_EMPLOYEE', 'WH_TERMINATION',
                      'WH_HEADCOUNT_MONTH', 'WH_REQUISITION', 'WH_METRIC',
                      'WH_METRIC_REQUEST', 'WH_ANSWER_LOG')
  AND COLUMN_NAME IS NULL
GROUP BY OBJECT_NAME
ORDER BY OBJECT_NAME;

-- Expected: one non-null column comment for every WH_ table column.
SELECT c.TABLE_NAME, COUNT(*) AS COLUMN_COUNT,
       SUM(CASE WHEN cc.COMMENTS IS NOT NULL THEN 1 ELSE 0 END) AS COMMENTED_COLUMNS
FROM USER_TAB_COLUMNS c
LEFT JOIN USER_COL_COMMENTS cc
  ON cc.TABLE_NAME = c.TABLE_NAME AND cc.COLUMN_NAME = c.COLUMN_NAME
WHERE c.TABLE_NAME IN ('WH_LOCATION', 'WH_EMPLOYEE', 'WH_TERMINATION',
                       'WH_HEADCOUNT_MONTH', 'WH_REQUISITION', 'WH_METRIC',
                       'WH_METRIC_REQUEST', 'WH_ANSWER_LOG')
GROUP BY c.TABLE_NAME
ORDER BY c.TABLE_NAME;
