-- Location-scoped application identities for Oracle AI Database 26ai.
-- Safe to rerun. No source data, credentials, or demo users are inserted.
-- Run after sql/04_portable_catalog.sql. All keys are organization-defined.

CREATE TABLE IF NOT EXISTS WH_APP_USER (
    USER_ID          VARCHAR2(128) NOT NULL,
    DISPLAY_NAME     VARCHAR2(200) NOT NULL,
    TOKEN_HASH       VARCHAR2(64) NOT NULL,
    ROLE             VARCHAR2(8) NOT NULL,
    STATUS           VARCHAR2(8) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY       VARCHAR2(128) NOT NULL,
    TOKEN_ROTATED_AT TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_AT       TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_BY       VARCHAR2(128),
    CONSTRAINT WH_AU_PK PRIMARY KEY (USER_ID),
    CONSTRAINT WH_AU_ID_CK CHECK (
        USER_ID = LOWER(TRIM(USER_ID))
        AND REGEXP_LIKE(USER_ID, '^[a-z0-9][a-z0-9._@+-]*$', 'c')
        AND NOT REGEXP_LIKE(USER_ID, '[[:cntrl:]]')
    ),
    CONSTRAINT WH_AU_TOKEN_UK UNIQUE (TOKEN_HASH),
    CONSTRAINT WH_AU_TOKEN_CK CHECK (REGEXP_LIKE(TOKEN_HASH, '^[0-9a-f]{64}$', 'c')),
    CONSTRAINT WH_AU_ROLE_CK CHECK (ROLE IN ('ADMIN', 'READER')),
    CONSTRAINT WH_AU_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT WH_AU_REVOKED_CK CHECK (
        STATUS = 'ACTIVE' OR (REVOKED_AT IS NOT NULL AND REVOKED_BY IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS WH_SEC_LOCATION (
    LOCATION_KEY VARCHAR2(128) NOT NULL,
    DISPLAY_NAME VARCHAR2(200) NOT NULL,
    STATUS       VARCHAR2(8) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(128) NOT NULL,
    STATUS_AT    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS_BY    VARCHAR2(128) NOT NULL,
    CONSTRAINT WH_SL_PK PRIMARY KEY (LOCATION_KEY),
    CONSTRAINT WH_SL_KEY_CK CHECK (
        LOCATION_KEY = UPPER(TRIM(LOCATION_KEY))
        AND REGEXP_LIKE(LOCATION_KEY, '^[A-Z0-9][A-Z0-9_.:-]*$', 'c')
        AND NOT REGEXP_LIKE(LOCATION_KEY, '[[:cntrl:]]')
    ),
    CONSTRAINT WH_SL_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS WH_USER_LOCATION (
    USER_ID      VARCHAR2(128) NOT NULL,
    LOCATION_KEY VARCHAR2(128) NOT NULL,
    STATUS       VARCHAR2(8) DEFAULT 'ACTIVE' NOT NULL,
    GRANTED_AT   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    GRANTED_BY   VARCHAR2(128) NOT NULL,
    REVOKED_AT   TIMESTAMP(6) WITH TIME ZONE,
    REVOKED_BY   VARCHAR2(128),
    CONSTRAINT WH_UL_PK PRIMARY KEY (USER_ID, LOCATION_KEY),
    CONSTRAINT WH_UL_USER_FK FOREIGN KEY (USER_ID) REFERENCES WH_APP_USER (USER_ID),
    CONSTRAINT WH_UL_LOCATION_FK FOREIGN KEY (LOCATION_KEY)
        REFERENCES WH_SEC_LOCATION (LOCATION_KEY),
    CONSTRAINT WH_UL_STATUS_CK CHECK (STATUS IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT WH_UL_REVOKED_CK CHECK (
        STATUS = 'ACTIVE' OR (REVOKED_AT IS NOT NULL AND REVOKED_BY IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS WH_ACCESS_AUDIT (
    EVENT_ID        NUMBER GENERATED ALWAYS AS IDENTITY,
    EVENT_AT        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ACTOR_USER_ID   VARCHAR2(128) NOT NULL,
    ACTION          VARCHAR2(24) NOT NULL,
    TARGET_USER_ID  VARCHAR2(128),
    LOCATION_KEY    VARCHAR2(128),
    CONSTRAINT WH_AA_PK PRIMARY KEY (EVENT_ID),
    CONSTRAINT WH_AA_ACTION_CK CHECK (ACTION IN (
        'BOOTSTRAP_ADMIN', 'CREATE_USER', 'ROTATE_TOKEN', 'REVOKE_USER',
        'REGISTER_LOCATION', 'SET_LOCATION_STATUS', 'GRANT_LOCATION',
        'REVOKE_LOCATION'
    ))
);

COMMENT ON TABLE WH_APP_USER IS 'Application identities. TOKEN_HASH is SHA-256 of a random bearer token; plaintext tokens are never stored.';
COMMENT ON COLUMN WH_APP_USER.USER_ID IS 'Canonical lowercase application user identifier.';
COMMENT ON COLUMN WH_APP_USER.TOKEN_HASH IS 'Lowercase SHA-256 hexadecimal verifier for a 256-bit random token.';
COMMENT ON COLUMN WH_APP_USER.ROLE IS 'ADMIN may manage access through privileged database procedures; READER may query approved metrics.';
COMMENT ON COLUMN WH_APP_USER.STATUS IS 'Revoked users cannot authenticate or answer questions.';
COMMENT ON TABLE WH_SEC_LOCATION IS 'Organization-defined canonical location keys; independent of any source schema.';
COMMENT ON COLUMN WH_SEC_LOCATION.LOCATION_KEY IS 'Uppercase key emitted by approved WH_ adapter views.';
COMMENT ON COLUMN WH_SEC_LOCATION.STATUS IS 'An inactive location is excluded from all scoped answers.';
COMMENT ON TABLE WH_USER_LOCATION IS 'Current grants. Active rows are checked at query time; revocation is immediate.';
COMMENT ON TABLE WH_ACCESS_AUDIT IS 'Administrative access changes only. It intentionally stores no token or token hash.';
