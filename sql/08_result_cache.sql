-- Optional, non-destructive result cache for certified portable metrics.
-- Install after the portable catalog and security schema. No policy is enabled
-- by this migration, and no source records or credentials are inserted.

CREATE TABLE IF NOT EXISTS WH_CACHE_STATE (
    STATE_ID         NUMBER(1) NOT NULL,
    ACCESS_REVISION  NUMBER(19) DEFAULT 0 NOT NULL,
    UPDATED_AT       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT WH_CS_PK PRIMARY KEY (STATE_ID),
    CONSTRAINT WH_CS_ID_CK CHECK (STATE_ID = 1),
    CONSTRAINT WH_CS_REV_CK CHECK (ACCESS_REVISION >= 0)
);

CREATE TABLE IF NOT EXISTS WH_CACHE_SOURCE (
    SOURCE_VIEW      VARCHAR2(128) NOT NULL,
    DATA_REVISION    NUMBER(19) DEFAULT 1 NOT NULL,
    UPDATED_AT       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY       VARCHAR2(128) NOT NULL,
    CONSTRAINT WH_CSO_PK PRIMARY KEY (SOURCE_VIEW),
    CONSTRAINT WH_CSO_VIEW_CK CHECK (REGEXP_LIKE(SOURCE_VIEW, '^WH_[A-Z0-9_$#]+$', 'c')),
    CONSTRAINT WH_CSO_REV_CK CHECK (DATA_REVISION >= 1)
);

CREATE TABLE IF NOT EXISTS WH_CACHE_POLICY (
    METRIC_ID         VARCHAR2(64) NOT NULL,
    METRIC_VERSION    NUMBER(10) NOT NULL,
    ENABLED           CHAR(1) DEFAULT 'N' NOT NULL,
    TTL_SECONDS       NUMBER(6) DEFAULT 1800 NOT NULL,
    POLICY_REVISION   NUMBER(19) DEFAULT 1 NOT NULL,
    UPDATED_AT        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY        VARCHAR2(128) NOT NULL,
    CONSTRAINT WH_CP_PK PRIMARY KEY (METRIC_ID, METRIC_VERSION),
    CONSTRAINT WH_CP_METRIC_FK FOREIGN KEY (METRIC_ID, METRIC_VERSION)
        REFERENCES WH_REGISTERED_METRIC (METRIC_ID, VERSION),
    CONSTRAINT WH_CP_ENABLED_CK CHECK (ENABLED IN ('Y', 'N')),
    CONSTRAINT WH_CP_TTL_CK CHECK (TTL_SECONDS BETWEEN 1 AND 86400),
    CONSTRAINT WH_CP_REV_CK CHECK (POLICY_REVISION >= 1)
);

CREATE TABLE IF NOT EXISTS WH_QUERY_CACHE (
    CACHE_KEY          VARCHAR2(64) NOT NULL,
    USER_ID            VARCHAR2(128) NOT NULL,
    METRIC_ID          VARCHAR2(64) NOT NULL,
    METRIC_VERSION     NUMBER(10) NOT NULL,
    SOURCE_VIEW        VARCHAR2(128) NOT NULL,
    SOURCE_DDL_SHA256  VARCHAR2(64) NOT NULL,
    ACCESS_REVISION    NUMBER(19) NOT NULL,
    DATA_REVISION      NUMBER(19) NOT NULL,
    POLICY_REVISION    NUMBER(19) NOT NULL,
    CANONICAL_JSON     CLOB NOT NULL,
    RESULT_JSON        CLOB NOT NULL,
    ROW_COUNT          NUMBER(5) NOT NULL,
    GENERATED_AT       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    EXPIRES_AT         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT WH_QC_PK PRIMARY KEY (CACHE_KEY),
    CONSTRAINT WH_QC_USER_FK FOREIGN KEY (USER_ID) REFERENCES WH_APP_USER (USER_ID),
    CONSTRAINT WH_QC_POLICY_FK FOREIGN KEY (METRIC_ID, METRIC_VERSION)
        REFERENCES WH_CACHE_POLICY (METRIC_ID, METRIC_VERSION),
    CONSTRAINT WH_QC_SOURCE_FK FOREIGN KEY (SOURCE_VIEW)
        REFERENCES WH_CACHE_SOURCE (SOURCE_VIEW),
    CONSTRAINT WH_QC_KEY_CK CHECK (REGEXP_LIKE(CACHE_KEY, '^[0-9a-f]{64}$', 'c')),
    CONSTRAINT WH_QC_DDL_CK CHECK (REGEXP_LIKE(SOURCE_DDL_SHA256, '^[0-9a-f]{64}$', 'c')),
    CONSTRAINT WH_QC_REVISIONS_CK CHECK (
        ACCESS_REVISION >= 0 AND DATA_REVISION >= 1 AND POLICY_REVISION >= 1
    ),
    CONSTRAINT WH_QC_REQUEST_JSON_CK CHECK (CANONICAL_JSON IS JSON),
    CONSTRAINT WH_QC_RESULT_JSON_CK CHECK (RESULT_JSON IS JSON),
    CONSTRAINT WH_QC_ROWS_CK CHECK (ROW_COUNT BETWEEN 1 AND 500),
    CONSTRAINT WH_QC_EXPIRY_CK CHECK (EXPIRES_AT > GENERATED_AT)
);

CREATE INDEX IF NOT EXISTS WH_QC_EXPIRY_IX ON WH_QUERY_CACHE (EXPIRES_AT);
CREATE INDEX IF NOT EXISTS WH_QC_USER_METRIC_IX
ON WH_QUERY_CACHE (USER_ID, METRIC_ID, METRIC_VERSION);

COMMENT ON TABLE WH_CACHE_STATE IS 'One transactional access revision. Security-table triggers increment it whenever current access state changes.';
COMMENT ON TABLE WH_CACHE_SOURCE IS 'Per-adapter data revision. The ingestion transaction must bump it when any underlying input changes.';
COMMENT ON TABLE WH_CACHE_POLICY IS 'Explicit cache opt-in and maximum freshness interval for one certified metric version.';
COMMENT ON TABLE WH_QUERY_CACHE IS 'Bounded, per-user certified result cache. Every hit rechecks current authorization, policy, source and view identity.';
COMMENT ON COLUMN WH_QUERY_CACHE.CACHE_KEY IS 'SHA-256 of canonical typed metric parameters, compiled SQL, authenticated user, and current revisions.';
COMMENT ON COLUMN WH_QUERY_CACHE.CANONICAL_JSON IS 'Typed query parameters and provenance only; no natural-language question or bearer token.';
COMMENT ON COLUMN WH_QUERY_CACHE.RESULT_JSON IS 'Rows produced by scoped certified SQL on a prior cache miss.';
COMMENT ON COLUMN WH_QUERY_CACHE.GENERATED_AT IS 'Oracle UTC timestamp captured before the certified source query began; TTL starts here.';
COMMENT ON COLUMN WH_QUERY_CACHE.EXPIRES_AT IS 'Upper bound for serving a cached result, even if revisions remain unchanged.';
COMMENT ON COLUMN WH_CACHE_POLICY.TTL_SECONDS IS 'Approved maximum result age in seconds; 1 to 86400.';
COMMENT ON COLUMN WH_CACHE_SOURCE.DATA_REVISION IS 'Increment in the same transaction as source ingestion or correction for strong freshness.';

COMMENT ON COLUMN WH_REGISTERED_ANSWER_LOG.CACHE_STATUS IS 'MISS or HIT for cache attempts; null for legacy, disabled, or bypassed answers. HIT does not execute SQL.';
COMMENT ON COLUMN WH_REGISTERED_ANSWER_LOG.CACHE_KEY IS 'Canonical result cache key when caching was attempted; never a bearer token.';
COMMENT ON COLUMN WH_REGISTERED_ANSWER_LOG.RESULT_GENERATED_AT IS 'Oracle UTC source-query start for a fresh result; a hit reuses that original timestamp.';
COMMENT ON COLUMN WH_REGISTERED_ANSWER_LOG.COMPILED_SQL IS 'Reviewed SQL provenance; a HIT reuses rows and does not execute this SQL again.';
